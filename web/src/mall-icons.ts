/**
 * 购买力商品图标：手绘技术线稿。
 *
 * 为什么不用 emoji：
 *   emoji 是字体，形状由系统决定（macOS / Windows / Android 各不相同），
 *   颜色固定、无法跟随主题，小尺寸下细节还会糊成一团。
 *   这里改成**同一套网格、同一笔粗细**的矢量线稿——正是界面已有的
 *   「制图」语言（发丝线、墨色、方角），商品也画成图纸上的样子。
 *
 * 所有图标画在 32×32 网格上：
 *   - 描边一律 1.4，圆头圆角
 *   - 图案控制在 3..29 之间，留出约 2 单位光学边距
 *   - 颜色一律 currentColor，浅色/深色、卡片/分享图里都能直接用
 *
 * 纯数据 + 纯函数，不依赖 React，不发起任何网络请求：
 * 分享卡片用 iconDataUrl() 把同一份路径序列化成 data URL 再画进 canvas。
 */

export interface IconSpec {
  /** 描边路径 */
  p?: string[];
  /** 描边圆角矩形 [x, y, w, h, rx] */
  r?: [number, number, number, number, number][];
  /** 描边圆 [cx, cy, r] */
  c?: [number, number, number][];
  /** 描边椭圆 [cx, cy, rx, ry, 旋转角度] */
  e?: [number, number, number, number, number][];
  /** 直线 [x1, y1, x2, y2] */
  l?: [number, number, number, number][];
  /** 淡填充路径（16% 不透明度，用来暗示玻璃/材质/屏幕） */
  t?: string[];
  /** 淡填充圆 */
  tc?: [number, number, number][];
  /** 实心路径（按键、卡口、镜头高光等细节） */
  f?: string[];
}

