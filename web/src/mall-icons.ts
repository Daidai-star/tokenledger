/** 图标都支持的 key（用于测试与类型约束） */
export const ICON_IDS = Object.keys(MALL_ICONS);

/**
 * 把图标序列化成 SVG 源码。
 *
 * 分享卡片要把同一个图标画进 canvas，而 canvas 不认 JSX，
 * 所以走「SVG 源码 -> data URL -> Image -> drawImage」。全程本地，不联网。
 */
export function iconSvgMarkup(id: string, color: string, size = 32): string {
  const spec = MALL_ICONS[id];
  if (!spec) return "";
  const parts: string[] = [];

  for (const [x, y, w, h, rx] of spec.r ?? []) {
    parts.push(`<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rx}" ry="${rx}"/>`);
  }
  for (const [cx, cy, rx, ry, deg] of spec.e ?? []) {
    parts.push(
      `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}"${deg ? ` transform="rotate(${deg} ${cx} ${cy})"` : ""}/>`,
    );
  }
  for (const [cx, cy, r] of spec.c ?? []) {
    parts.push(`<circle cx="${cx}" cy="${cy}" r="${r}"/>`);
  }
  for (const [x1, y1, x2, y2] of spec.l ?? []) {
    parts.push(`<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`);
  }
  for (const d of spec.p ?? []) parts.push(`<path d="${d}"/>`);

  const tints = [...(spec.t ?? []).map((d) => `<path d="${d}"/>`)];
  for (const [cx, cy, r] of spec.tc ?? []) {
    tints.push(`<circle cx="${cx}" cy="${cy}" r="${r}"/>`);
  }
  if (tints.length) {
    parts.push(`<g fill="${color}" fill-opacity="0.16" stroke="none">${tints.join("")}</g>`);
  }
  if (spec.f?.length) {
    parts.push(
      `<g fill="${color}" stroke="none">${spec.f.map((d) => `<path d="${d}"/>`).join("")}</g>`,
    );
  }

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${GRID} ${GRID}" width="${size}" height="${size}" ` +
    `fill="none" stroke="${color}" stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round">` +
    parts.join("") +
    `</svg>`
  );
}

/** 图标的 data URL（给 canvas 用） */
export function iconDataUrl(id: string, color: string, size = 32): string {
  const svg = iconSvgMarkup(id, color, size);
  return svg ? `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}` : "";
}

