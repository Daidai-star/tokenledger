/**
 * 页面分栏配置。
 *
 * 之前 16 个区块从上到下排成一条 14000px 的长卷，读者要一直滚——
 * 这是把「文档」当「应用」做。分栏的判断依据是**语义**，不是视觉：
 * 一个读者来这个页面，问的其实是四个不同的问题。
 *
 *   总览   我整体用了多少？          → 本月用量与成本 + 趋势 + 速率
 *   项目   钱花在哪个项目上？        → 项目账单
 *   诊断   我有什么浪费、怎么改？    → 冷启动 / 浪费 / 护栏 / 额度
 *   购买力 这笔钱意味着什么？        → 折成实物 + 分享卡片
 *   明细   具体是哪些模型和会话？    → 排行 / 热力图 / 矩阵 / 流
 *
 * 顺序按「先回答问题、再给证据」排：诊断在最前是因为它给的是行动建议，
 * 明细放最后因为它是查证用的，不是每天都要看。
 */

export interface SectionDef {
  /** 标签页上的短名 */
  name: string;
  /** 一句话说明这栏回答什么问题 */
  hint: string;
  /** section 元素的 h2 文本，用来定位 DOM */
  sections: string[];
}

