/** 首屏 profile 区（标题 + 四个数字 + 洞察条），它不属于任何一栏，单独保留在顶部 */
export const HERO_SECTIONS = ["本机 Coding 用量"];

/** 当前分栏包含哪些区块 */
export function sectionsInTab(name: string): string[] {
  return TABS.find((t) => t.name === name)?.sections ?? [];
}
